"""Supplementary Note 1 as LaTeX for the supplement.

    python3 manuscript/make_sn1.py

converts ``experiment/Supplementary_Note_1_Reproducibility.md`` with pandoc
(its Markdown, so that wide tables wrap) into ``manuscript/sn1.tex``, sets
in math the few characters the text font lacks, and lets the long paths and
commands in ``\\texttt`` break after a slash, an underscore or a comma.
"""

import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "experiment" / "Supplementary_Note_1_Reproducibility.md"
CHARS = {"⌈": r"\ensuremath{\lceil}", "⌉": r"\ensuremath{\rceil}", "−": r"\ensuremath{-}"}


def breakable(tex: str) -> str:
    """Every ``\\texttt{...}`` (braces balanced) with a break allowed after ``/``, ``\\_`` and ``,``."""
    out, i = [], 0
    for m in re.finditer(r"\\texttt\{", tex):
        if m.start() < i:
            continue
        j, depth = m.end(), 1
        while depth:
            depth += {"{": 1, "}": -1}.get(tex[j], 0) if tex[j - 1] != "\\" else 0
            j += 1
        body = tex[m.end():j - 1]
        body = re.sub(r"(/|\\_|,)", r"\1\\allowbreak{}", body)
        out.append(tex[i:m.start()] + r"\texttt{" + body + "}")
        i = j
    return "".join(out) + tex[i:]


def main() -> None:
    tex = subprocess.run(
        ["pandoc", str(SOURCE), "-f", "markdown", "-t", "latex", "--columns=72", "--wrap=preserve",
         "--syntax-highlighting=none"],
        check=True, capture_output=True, text=True).stdout
    for ch, rep in CHARS.items():
        tex = tex.replace(ch, rep)
    (HERE / "sn1.tex").write_text(
        "% Generated by manuscript/make_sn1.py from experiment/Supplementary_Note_1_Reproducibility.md; do not edit.\n"
        + breakable(tex))
    print("wrote sn1.tex")


if __name__ == "__main__":
    main()
